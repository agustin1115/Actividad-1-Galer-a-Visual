function normalizar(texto) {
  return texto.toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '');
}

function palabrasDe(texto) {
  return normalizar(texto).split(/[^a-z0-9]+/).filter(function (palabra) {
    return palabra && PALABRAS_VACIAS.indexOf(palabra) === -1;
  });
}

function raiz(palabra) {
  if (palabra.length <= 4) return palabra;
  return palabra.replace(/(es|s)$/, '').replace(/(ar|er|ir|a|e|o)$/, '');
}

function distancia(a, b) {
  var fila = [];
  for (var j = 0; j <= b.length; j++) fila[j] = j;
  for (var i = 1; i <= a.length; i++) {
    var diagonal = fila[0];
    fila[0] = i;
    for (var k = 1; k <= b.length; k++) {
      var anterior = fila[k];
      fila[k] = Math.min(fila[k] + 1, fila[k - 1] + 1, diagonal + (a[i - 1] === b[k - 1] ? 0 : 1));
      diagonal = anterior;
    }
  }
  return fila[b.length];
}

// 1 si es la misma palabra, menos si es un comienzo o un error de tipeo, 0 si no coincide.
function parecido(buscada, palabra) {
  if (buscada === palabra || raiz(buscada) === raiz(palabra)) return 1;
  if (buscada.length >= 3 && palabra.indexOf(buscada) === 0) return 0.8;
  if (buscada.length >= 5 && Math.abs(buscada.length - palabra.length) <= 2) {
    if (distancia(buscada, palabra) <= (buscada.length >= 9 ? 2 : 1)) return 0.6;
  }
  return 0;
}

function mejorParecido(buscada, palabras) {
  return palabras.reduce(function (mejor, palabra) {
    return Math.max(mejor, parecido(buscada, palabra));
  }, 0);
}

var INDICE = PREGUNTAS.map(function (item) {
  return {
    item: item,
    pregunta: palabrasDe(item.pregunta),
    claves: palabrasDe(item.claves),
    respuesta: palabrasDe(item.respuesta)
  };
});

// Las palabras que aparecen en pocas preguntas distinguen mejor y pesan más.
function pesoDe(buscada) {
  var cuantas = INDICE.filter(function (entrada) {
    return mejorParecido(buscada, entrada.pregunta.concat(entrada.claves, entrada.respuesta)) > 0;
  }).length;
  return 1 + Math.log(INDICE.length / (1 + cuantas));
}

function existeTal(buscada) {
  return INDICE.some(function (entrada) {
    return mejorParecido(buscada, entrada.pregunta.concat(entrada.claves, entrada.respuesta)) >= 0.8;
  });
}

function puntuar(entrada, buscadas, frase) {
  var total = 0;
  var encontradas = 0;
  buscadas.forEach(function (buscada) {
    var valor = Math.max(
      mejorParecido(buscada, entrada.pregunta) * 3,
      mejorParecido(buscada, entrada.claves) * 2.5,
      mejorParecido(buscada, entrada.respuesta)
    );
    // Si la palabra existe en el sitio, no se la trata como error de tipeo (plaza no es plata).
    if (valor > 0 && mejorParecido(buscada, entrada.pregunta.concat(entrada.claves, entrada.respuesta)) < 0.8 && existeTal(buscada)) {
      valor = 0;
    }
    if (valor > 0) {
      total += valor * pesoDe(buscada);
      encontradas++;
    }
  });
  if (!buscadas.length) return 0;
  var puntos = total * encontradas / buscadas.length;
  // Si la búsqueda es parte textual de la pregunta, es casi seguro la que se busca.
  return normalizar(entrada.item.pregunta).indexOf(frase) !== -1 ? puntos * 2 : puntos;
}

function buscarEn(texto, categoria) {
  var buscadas = palabrasDe(texto);
  var hayTexto = texto.trim() !== '';

  var resultados = INDICE
    .map(function (entrada, indice) {
      return { item: entrada.item, indice: indice, puntos: hayTexto ? puntuar(entrada, buscadas, normalizar(texto.trim())) : 0 };
    })
    .filter(function (resultado) {
      var enCategoria = categoria === 'Todas' || resultado.item.categoria === categoria;
      return enCategoria && (!hayTexto || resultado.puntos > 0);
    })
    .sort(function (a, b) {
      return b.puntos - a.puntos || a.indice - b.indice;
    });

  // Solo se muestran las respuestas cercanas a la mejor, para no llenar la lista de ruido.
  var minimo = resultados.length ? resultados[0].puntos * 0.5 : 0;
  return resultados
    .filter(function (resultado) {
      return resultado.puntos >= minimo;
    })
    .map(function (resultado) {
      return resultado.item;
    });
}

function crearPregunta(item, indice, abierta) {
  var li = document.createElement('li');
  li.className = 'rounded-lg border border-techo-100 bg-white';

  var titulo = document.createElement('h3');
  var boton = document.createElement('button');
  var idRespuesta = 'respuesta-' + indice;
  boton.type = 'button';
  boton.className = 'flex w-full items-start justify-between gap-4 rounded-lg p-4 text-left font-titulos font-bold text-techo-900 hover:bg-techo-50';
  boton.setAttribute('aria-expanded', abierta ? 'true' : 'false');
  boton.setAttribute('aria-controls', idRespuesta);

  var texto = document.createElement('span');
  texto.textContent = item.pregunta;
  var signo = document.createElement('span');
  signo.setAttribute('aria-hidden', 'true');
  signo.className = 'text-xl leading-none';
  signo.textContent = abierta ? '−' : '+';
  boton.appendChild(texto);
  boton.appendChild(signo);
  titulo.appendChild(boton);

  var panel = document.createElement('div');
  panel.id = idRespuesta;
  panel.className = 'px-4 pb-4';
  panel.hidden = !abierta;

  var parrafo = document.createElement('p');
  parrafo.textContent = item.respuesta;
  var enlace = document.createElement('a');
  enlace.href = item.enlace.url;
  enlace.className = 'mt-2 inline-block font-bold text-techo-900 underline underline-offset-2 hover:text-naranja-700';
  enlace.textContent = item.enlace.texto;
  panel.appendChild(parrafo);
  panel.appendChild(enlace);

  boton.addEventListener('click', function () {
    var estabaAbierta = boton.getAttribute('aria-expanded') === 'true';
    boton.setAttribute('aria-expanded', estabaAbierta ? 'false' : 'true');
    signo.textContent = estabaAbierta ? '+' : '−';
    panel.hidden = estabaAbierta;
  });

  li.appendChild(titulo);
  li.appendChild(panel);
  return li;
}

function mostrarPreguntas() {
  var texto = campoBusqueda.value;
  var hayTexto = texto.trim() !== '';
  var resultados = buscarEn(texto, categoriaActiva);

  listaPreguntas.innerHTML = '';
  resultados.forEach(function (item, indice) {
    listaPreguntas.appendChild(crearPregunta(item, indice, hayTexto && indice === 0));
  });

  sinResultados.classList.toggle('hidden', resultados.length > 0);
  botonLimpiar.classList.toggle('hidden', !hayTexto);

  var cantidad = resultados.length === 1 ? '1 pregunta' : resultados.length + ' preguntas';
  var filtro = categoriaActiva === 'Todas' ? '' : ' en ' + categoriaActiva;
  estadoPreguntas.textContent = hayTexto
    ? cantidad + filtro + ' para "' + texto.trim() + '". La más cercana aparece abierta.'
    : cantidad + filtro + '.';

  if (hayTexto && !resultados.length && categoriaActiva !== 'Todas' && buscarEn(texto, 'Todas').length) {
    estadoPreguntas.textContent = 'No hay resultados en ' + categoriaActiva + ', pero sí en otros temas. Elegí Todas para verlos.';
  }
}

